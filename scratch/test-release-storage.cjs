const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { app } = require('electron');
const appRoot = process.env.ASSISTANT_TEST_APP_ROOT;
if (!appRoot || !appRoot.includes('app.asar')) throw new Error('Expected a packaged app.asar');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'metech-release-storage-'));
const profile = path.join(root, 'profile'), legacy = path.join(root, 'legacy');
fs.mkdirSync(profile); fs.mkdirSync(legacy);
app.setPath('userData', profile);
app.whenReady().then(() => {
  const { getStoragePath } = require(path.join(appRoot, 'electron/storage-utils.cjs'));
  const migrated = { marker: 'fake-legacy-test', enabled: false };
  fs.writeFileSync(path.join(legacy, 'email-config.json'), JSON.stringify(migrated));
  const file = getStoragePath('email-config.json', { legacyDir: legacy });
  assert.equal(file, path.join(profile, 'email-config.json'));
  assert.deepEqual(JSON.parse(fs.readFileSync(file, 'utf8')), migrated);
  fs.writeFileSync(file, JSON.stringify({ marker: 'current-test-profile' }));
  getStoragePath('email-config.json', { legacyDir: legacy });
  assert.equal(JSON.parse(fs.readFileSync(file, 'utf8')).marker, 'current-test-profile');
  const { DesktopOrganizer } = require(path.join(appRoot, 'electron/desktop-organizer.cjs'));
  const service = new DesktopOrganizer({ organizerDesktopIcons: false, organizerDrag: {} }, profile);
  assert.equal(service.boards.length, 0, 'fresh package profile has no personal data');
  service.save();
  const restarted = new DesktopOrganizer({ organizerDesktopIcons: false, organizerDrag: {} }, profile);
  assert.equal(restarted.boards.length, 0);
  console.log('Packaged services: isolated first profile, settings write/read and one-time legacy migration passed.');
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
app.on('will-quit', () => { try { fs.rmSync(root, { recursive: true, force: true }); } catch {} });
