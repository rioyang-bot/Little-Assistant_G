const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const electron = require('electron');
const { app } = electron;
const { DesktopOrganizer } = require('../electron/desktop-organizer.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'organizer-visibility-'));
app.setPath('userData', dir);
let service;
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  try {
    service = new DesktopOrganizer({ ...electron, organizerDesktopIcons:false, organizerDrag:{} }, dir);
    service.register(); service.create();
    const board = service.boards[0], win = service.windows.get(board.id);
    await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    await win.webContents.executeJavaScript(`window.electronAPI.invoke('organizer-update', { title:'設備文件',color:'#00ff00',opacity:100 })`);
    const reloaded=new Promise(resolve=>win.webContents.once('did-finish-load',resolve)); win.reload(); await reloaded;
    assert.equal(win.getTitle(), '設備文件');
    assert.equal(win.webContents.getBackgroundThrottling(),false);
    win.hide(); assert.equal(win.isVisible(),false);
    service.show(board); assert.equal(win.isVisible(),true);
    win.minimize();
    for(let i=0;i<50 && !win.isMinimized();i++) await delay(20);
    assert.equal(win.isMinimized(),true);
    service.show(board);
    for(let i=0;i<50 && win.isMinimized();i++) await delay(20);
    assert.equal(win.isMinimized(),false); assert.equal(win.isVisible(),true);
    win.setBounds({ x:50000,y:50000,width:360,height:300 });
    service.show(board);
    const bounds=win.getBounds(), fitted=service.fitBounds(bounds);
    for(const key of ['x','y','width','height']) assert.ok(Math.abs(bounds[key]-fitted[key])<=1,'restored bounds must fit within DPI rounding tolerance');
    assert.equal(win.isAlwaysOnTop(),false,'restoration retains the desktop bottom layer');
    await delay(250);
    const captured = await win.webContents.capturePage();
    const { PNG } = require('pngjs'); const image = PNG.sync.read(captured.toPNG());
    let greenPixels=0;
    for(let i=0;i<image.data.length;i+=4) if(image.data[i+1]>180 && image.data[i]<60 && image.data[i+2]<60) greenPixels++;
    assert.ok(greenPixels>image.width*image.height/2,'restored organizer must render its background instead of remaining blank');
    console.log('Organizer visibility: hidden/minimized restore, off-screen recovery, title, background rendering and bottom layer passed.');

    const originalFile=path.join(dir,'original.txt'); fs.writeFileSync(originalFile,'recovery fixture');
    board.items=[{id:'recovery-item',path:originalFile,position:{x:8,y:12}}];
    board.locked=true; board.headerColorMode='custom'; board.headerColor='#123456'; board.textColor='#abcdef';
    service.save();
    service.create();
    const sibling=service.boards[1], siblingWindow=service.windows.get(sibling.id);
    siblingWindow.setBounds({x:250,y:40,width:420,height:280});
    await new Promise(resolve=>siblingWindow.once('ready-to-show',resolve));
    const earlyBounds=siblingWindow.getBounds();
    assert.ok(Math.abs(earlyBounds.x-250)<=1 && Math.abs(earlyBounds.y-40)<=1,'initial painting must not overwrite a position set before load');
    const siblingSnapshot=JSON.stringify(sibling);
    const snapshot=JSON.parse(JSON.stringify(board)); delete snapshot.bounds; delete snapshot.layouts;
    service.activeDrag={};
    await assert.rejects(service.recover(board),/拖曳/);
    assert.equal(win.isDestroyed(),false,'recovery must not destroy an active drag source');
    service.activeDrag=null;
    // A live DOM can coexist with a blank surface; show alone retains it.
    await win.webContents.executeJavaScript("document.getElementById('board').style.visibility='hidden'");
    service.show(board);
    assert.equal(await win.webContents.executeJavaScript("getComputedStyle(document.getElementById('board')).visibility"),'hidden');
    const firstRecovery=service.recover(board);
    assert.equal(service.recover(board),firstRecovery,'repeated recovery clicks share one operation');
    assert.equal(await firstRecovery,true);
    const recovered=service.windows.get(board.id);
    assert.notEqual(recovered,win); assert.equal(win.isDestroyed(),true);
    assert.equal(recovered.isVisible(),true); assert.equal(recovered.isAlwaysOnTop(),false);
    assert.equal(recovered.isMovable(),false,'recovery preserves locking');
    assert.equal(await recovered.webContents.executeJavaScript("getComputedStyle(document.getElementById('board')).visibility"),'visible');
    const expectedBounds=service.fitBounds(board.bounds);
    for(const key of ['x','y','width','height']) assert.ok(Math.abs(recovered.getBounds()[key]-expectedBounds[key])<=1,JSON.stringify({key,actual:recovered.getBounds(),expected:expectedBounds,stored:board.bounds}));
    for(const key of ['x','y','width','height']) assert.ok(Math.abs(board.layouts[service.displayKey()][key]-board.bounds[key])<=1,'the recovered position becomes the layout for these displays');
    const after=JSON.parse(JSON.stringify(board)); delete after.bounds; delete after.layouts;
    assert.deepEqual(after,snapshot,'recovery preserves ids, original paths, placements and appearance');
    assert.equal(fs.readFileSync(originalFile,'utf8'),'recovery fixture');
    assert.equal(service.windows.get(sibling.id),siblingWindow); assert.equal(JSON.stringify(sibling),siblingSnapshot);
    win.emit('closed');
    assert.equal(service.windows.get(board.id),recovered,'late retired-window events must not remove the new window');
    const recoveredImage=PNG.sync.read((await recovered.webContents.capturePage()).toPNG());
    let recoveredGreen=0;
    for(let i=0;i<recoveredImage.data.length;i+=4) if(recoveredImage.data[i+1]>180 && recoveredImage.data[i]<60 && recoveredImage.data[i+2]<60) recoveredGreen++;
    assert.ok(recoveredGreen>recoveredImage.width*recoveredImage.height/2,'recreated transparent window actually renders');
    await delay(250);
    const persisted=new DesktopOrganizer({organizerDesktopIcons:false,organizerDrag:{}},dir).boards.find(candidate=>candidate.id===board.id);
    const persistedSnapshot=JSON.parse(JSON.stringify(persisted)); delete persistedSnapshot.bounds; delete persistedSnapshot.layouts;
    assert.deepEqual(persisted.layouts,board.layouts,'display layouts survive restart');
    assert.deepEqual(persistedSnapshot,snapshot,'recovery survives restart');
    board.locked=false;
    await service.openSettings(board);
    const settings=service.settingsWindows.get(board.id);
    await settings.window.webContents.executeJavaScript("window.electronAPI.invoke('organizer-settings-preview',{color:'#ff0000'})");
    assert.equal(settings.preview.color,'#ff0000');
    assert.equal(await service.recover(board),true);
    assert.equal(settings.window.isDestroyed(),true);
    assert.equal(service.settingsWindows.has(board.id),false,'recovery releases the modal settings lifecycle');
    assert.equal(board.color,'#00ff00','unsaved preview is cancelled instead of changing saved appearance');
    const finalWindow=service.windows.get(board.id);
    assert.equal(finalWindow.isAlwaysOnTop(),false);
    assert.equal(await finalWindow.webContents.executeJavaScript("getComputedStyle(document.getElementById('board')).visibility"),'visible');
    console.log('Organizer recovery: blank live renderer replaced, current-screen bounds, lock/data/appearance retained, duplicate requests coalesced, sibling untouched and restart verified.');
  } catch(error) { console.error(error); process.exitCode=1; }
  finally { service?.dispose(); app.exit(process.exitCode||0); }
});
